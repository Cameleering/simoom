#!/usr/bin/env bash
# simoom cloud benchmark orchestrator: runs on your machine and drives the droplets made by
# droplets.sh over SSH. One server node runs one competitor at a time; three load nodes run
# simoom-bench agents, coordinated from load1.
#
#   bench/cloud/run.sh setup      ship the source, prepare every node (competitors in SERVERS)
#   bench/cloud/run.sh bench      run SCENARIOS for every server in SERVERS
#   bench/cloud/run.sh summary    regenerate the Markdown tables from the results
#   bench/cloud/run.sh all        setup, bench, summary
#
# Environment:
#   SERVERS     competitors (default: simoom nginx h2o actix hyper fasthttp)
#   SCENARIOS   S1 S3 S6 (default: S1 S6); S1 sweeps CONNS, S3 is the 1 KB JSON echo at 256
#               connections, S6 holds IDLE_CONNS idle connections
#   CONNS       S1 connection counts (default: 64 256 1024)
#   IDLE_CONNS  S6 connection counts (default: 10000 100000)
#   LABEL       results directory suffix (default: smoke) -> bench/results/<date>-<label>/
#   SWEEP_ARGS  extra simoom-bench sweep options (default: a short smoke plan)
#   CAMELEER_SRC  Cameleer checkout to ship when SERVERS has cameleer
#
# Results: raw RESULT/SLO/METRIC/IDLE/COLDSTART/SIZE/VERSION lines in results.txt, the
# HdrHistogram files of every measured point, machine.txt (kernel, sysctls, CPU, versions),
# sar logs, and summary.md generated by summarize.py.
set -euo pipefail
export MSYS_NO_PATHCONV=1  # Git Bash on Windows: keep remote /root/... arguments as they are

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
STATE_DIR="${BENCH_STATE:-$ROOT/target-bench/cloud}"
STATE="$STATE_DIR/droplets.txt"
KEY="${DO_SSH_KEY:-$HOME/.ssh/id_ed25519}"
SERVERS="${SERVERS:-simoom nginx h2o actix hyper fasthttp}"
SCENARIOS="${SCENARIOS:-S1 S6}"
CONNS="${CONNS:-64 256 1024}"
IDLE_CONNS="${IDLE_CONNS:-10000 100000}"
LABEL="${LABEL:-smoke}"
OUT="${BENCH_OUT:-$ROOT/bench/results/$(date -u +%Y-%m-%d)-$LABEL}"
SWEEP_ARGS="${SWEEP_ARGS:---probe 4 --step-warmup 2 --step 8 --steps 7 --point-warmup 3 --point 10}"
CAMELEER_SRC="${CAMELEER_SRC:-}"

[ -f "$STATE" ] || { echo "no $STATE: run droplets.sh up first" >&2; exit 1; }
field() { awk -v n="$1" -v c="$2" '$1==n {print $c}' "$STATE"; }
S_PUB=$(field simoom-bench-srv 2); S_PRIV=$(field simoom-bench-srv 3)
L_PUB=(); L_PRIV=()
for i in 1 2 3; do L_PUB+=("$(field simoom-bench-load$i 2)"); L_PRIV+=("$(field simoom-bench-load$i 3)"); done
AGENTS="$(printf '%s:7070,' "${L_PRIV[@]}")"; AGENTS="${AGENTS%,}"
SSH_OPTS=(-i "$KEY" -o StrictHostKeyChecking=accept-new -o UserKnownHostsFile="$STATE_DIR/known_hosts" -o ServerAliveInterval=30 -o BatchMode=yes -o ConnectTimeout=15)
on() { local h=$1; shift; ssh "${SSH_OPTS[@]}" "root@$h" "$@"; }
log() { printf '==> %s %s\n' "$(date -u +%H:%M:%S)" "$*" >&2; }
SB=/root/simoom/target/release/simoom-bench
SRV=/root/simoom/bench/competitors/server.sh
NODE="bash /root/simoom/bench/cloud/node.sh"

ship() {
  mkdir -p "$STATE_DIR"
  log "packing the simoom working tree (tracked and untracked files, no targets)"
  tar -C "$ROOT" --exclude='./target*' --exclude='./.git' --exclude='./bench/results' --exclude='*/target' -czf "$STATE_DIR/simoom.tgz" .
  local rev; rev="$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)+worktree"
  for h in "$S_PUB" "${L_PUB[@]}"; do
    scp -q "${SSH_OPTS[@]}" "$STATE_DIR/simoom.tgz" "root@$h:/root/simoom.tgz" &
  done
  wait
  for h in "$S_PUB" "${L_PUB[@]}"; do
    on "$h" "rm -rf /root/simoom && mkdir -p /root/simoom && tar -xzf /root/simoom.tgz -C /root/simoom 2>/dev/null && echo $rev > /root/simoom/REVISION && chmod +x /root/simoom/bench/*/*.sh /root/simoom/bench/competitors/*/*.sh"
  done
  case " $SERVERS " in *" cameleer "*)
    [ -n "$CAMELEER_SRC" ] || { echo "SERVERS has cameleer: set CAMELEER_SRC" >&2; exit 1; }
    git -C "$CAMELEER_SRC" archive --format=tar.gz -o "$STATE_DIR/cameleer.tgz" HEAD
    scp -q "${SSH_OPTS[@]}" "$STATE_DIR/cameleer.tgz" "root@$S_PUB:/root/cameleer.tgz"
    on "$S_PUB" 'rm -rf /root/cameleer && mkdir -p /root/cameleer && tar -xzf /root/cameleer.tgz -C /root/cameleer' ;;
  esac
}

setup() {
  ship
  mkdir -p "$OUT"
  log "preparing the nodes in parallel (logs in $STATE_DIR/setup-*.log)"
  on "$S_PUB" "bash /root/simoom/bench/cloud/setup-node.sh server '$SERVERS'" >"$STATE_DIR/setup-srv.log" 2>&1 &
  for i in 0 1 2; do
    on "${L_PUB[$i]}" "bash /root/simoom/bench/cloud/setup-node.sh load ${L_PRIV[$i]}" >"$STATE_DIR/setup-load$((i + 1)).log" 2>&1 &
  done
  local failed=0
  for j in $(jobs -p); do wait "$j" || failed=1; done
  for f in "$STATE_DIR"/setup-*.log; do echo "--- $f"; tail -n 4 "$f"; done
  grep -h "SETUP FAILED" "$STATE_DIR"/setup-srv.log || true
  [ "$failed" = 0 ] || { echo "setup failed, see $STATE_DIR/setup-*.log" >&2; exit 1; }
}

machine() { # machine NAME HOST
  on "$2" "bash -s" <<'EOF' | sed "s/^/$1 /"
echo "cpu: $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2- | sed 's/^ *//')"
echo "vcpus: $(nproc)"
echo "ram: $(awk '/MemTotal/ {printf "%.1f GiB", $2/1048576}' /proc/meminfo)"
echo "os: $(. /etc/os-release && echo "$PRETTY_NAME") kernel $(uname -r)"
echo "governor: $(cat /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor 2>/dev/null || echo n/a)"
for k in net.core.somaxconn net.ipv4.tcp_max_syn_backlog net.core.busy_poll net.core.busy_read net.ipv4.ip_local_port_range net.core.netdev_max_backlog; do echo "sysctl $k = $(sysctl -n $k | tr '\t' ' ')"; done
echo "nic: $(ip -o -4 addr show | awk '{print $2, $4}' | tr '\n' ' ')"
echo "rust: $(/root/.cargo/bin/rustc -V 2>/dev/null)"
echo "io_uring_disabled: $(sysctl -n kernel.io_uring_disabled 2>/dev/null || echo n/a)"
echo "perf cycles: $(perf stat -e cycles -x, true 2>&1 | head -1 | cut -d, -f1)"
EOF
}

server_bench() { # server_bench NAME
  local n=$1 res="$OUT/results.txt"
  log "== $n"
  on "$S_PUB" "$SRV stop" >/dev/null 2>&1 || true
  if ! on "$S_PUB" "b=\$($SRV binary $n 2>/dev/null); [ -n \"\$b\" ] && [ -x \"\$b\" ]"; then
    echo "SKIPPED server=$n reason=setup-failed" | tee -a "$res"
    return 0
  fi
  echo "VERSION server=$n $(on "$S_PUB" "$SRV version $n" | tr '\n' ' ')" | tee -a "$res"
  # size: the stripped main executable (a stripped copy; the original is untouched)
  on "$S_PUB" "b=\$($SRV binary $n); cp \"\$b\" /tmp/size.bin && strip -s /tmp/size.bin 2>/dev/null; echo \"SIZE server=$n bytes=\$(stat -c %s /tmp/size.bin) unstripped=\$(stat -c %s \"\$b\") path=\$b\"" | tee -a "$res"
  log "$n: cold start"
  on "$S_PUB" "$SB coldstart --addr 127.0.0.1:8080 --repeat 10 --label 'server=$n' -- \$($SRV cmd $n)" 2>&1 | grep -E '^COLDSTART|simoom-bench:' | tee -a "$res" || true
  on "$S_PUB" "$SRV start $n" || { echo "FAILED server=$n step=start" | tee -a "$res"; return 0; }
  on "$S_PUB" "$NODE idle-base; echo \"BASE server=$n pss_kb=\$(cat /root/node/pss0) mem_kb=\$($SRV mem | cut -d' ' -f1)\"" | tee -a "$res"
  on "$S_PUB" "$NODE pss-begin"
  local url="http://$S_PRIV:8080/"
  case " $SCENARIOS " in *" S1 "*)
    for c in $CONNS; do
      log "$n: S1 sweep, $c connections"
      on "${L_PUB[0]}" "mkdir -p /root/out && $SB sweep --url $url --conns $c --agents $AGENTS $SWEEP_ARGS --label 'server=$n scenario=S1 conns=$c' --out /root/out/$n-S1-c$c" 2>>"$OUT/run.log" \
        | grep -E '^(RESULT|SLO)' | tee -a "$res" || echo "FAILED server=$n scenario=S1 conns=$c" | tee -a "$res"
    done
    # cost per request at 80% of the SLO throughput at 256 connections (or the first level)
    local mc=256; case " $CONNS " in *" 256 "*) ;; *) mc=$(echo $CONNS | awk '{print $1}') ;; esac
    local slo; slo=$(grep "^SLO server=$n scenario=S1 conns=$mc " "$res" | grep -o 'slo_rps=[0-9]*' | tail -1 | cut -d= -f2)
    if [ -n "$slo" ] && [ "$slo" -gt 0 ]; then
      local rate=$(( slo * 8 / 10 )) secs=15 warm=4
      log "$n: cost per request at $rate req/s ($mc connections)"
      on "$S_PUB" "$NODE sar-begin $n $((secs + warm + 8)); $NODE cost-begin $secs $((warm + 2))" || true
      on "${L_PUB[0]}" "$NODE sar-begin $n $((secs + warm + 8))" || true
      on "${L_PUB[0]}" "$SB load --url $url --conns $mc --rate $rate --agents $AGENTS --warmup $warm --duration $secs --label 'server=$n scenario=cost conns=$mc'" 2>>"$OUT/run.log" | grep '^RESULT' | tee -a "$res" > "$STATE_DIR/cost.txt" || true
      local recv; recv=$(grep -o 'received=[0-9]*' "$STATE_DIR/cost.txt" | cut -d= -f2)
      sleep 2
      on "$S_PUB" "$NODE cost-end $n $mc ${recv:-0} $secs $((secs + warm))" | tee -a "$res" || true
      sleep 4
      on "$S_PUB" "$NODE nic $n 'server=$n node=srv'" | tee -a "$res" || true
      on "${L_PUB[0]}" "$NODE nic $n 'server=$n node=load1'" | tee -a "$res" || true
    fi ;;
  esac
  case " $SCENARIOS " in *" S3 "*)
    log "$n: S3 1 KB JSON echo, 256 connections"
    on "${L_PUB[0]}" "mkdir -p /root/out && $SB sweep --url http://$S_PRIV:8080/echo --body-size 1024 --conns 256 --agents $AGENTS $SWEEP_ARGS --label 'server=$n scenario=S3 conns=256' --out /root/out/$n-S3" 2>>"$OUT/run.log" \
      | grep -E '^(RESULT|SLO)' | tee -a "$res" || echo "FAILED server=$n scenario=S3" | tee -a "$res" ;;
  esac
  on "$S_PUB" "$NODE pss-end $n" | tee -a "$res" || true
  case " $SCENARIOS " in *" S6 "*)
    for ic in $IDLE_CONNS; do
      log "$n: S6 $ic idle connections"
      on "$S_PUB" "$SRV start $n && $NODE idle-base" || { echo "FAILED server=$n step=start-idle" | tee -a "$res"; continue; }
      local hold=30
      on "${L_PUB[0]}" "$SB load --url $url --idle --conns $ic --agents $AGENTS --warmup 0 --duration $hold --connect-threads 64 --label 'server=$n scenario=S6 conns=$ic'" 2>>"$OUT/run.log" | grep '^RESULT' >> "$res" &
      local lp=$! got="" est=0
      # sample once the connections are all open (the agents connect first, then hold)
      for _ in $(seq 90); do
        sleep 2
        est=$(on "$S_PUB" "$NODE established")
        if [ "$est" -ge $((ic * 99 / 100)) ]; then
          sleep 5
          got=$(on "$S_PUB" "$NODE idle $n $ic")
          break
        fi
        kill -0 $lp 2>/dev/null || break
      done
      wait $lp || true
      echo "${got:-IDLE server=$n conns=$ic failed=1 established=$est}" | tee -a "$res"
    done ;;
  esac
  on "$S_PUB" "$SRV stop" >/dev/null 2>&1 || true
}

bench() {
  mkdir -p "$OUT"
  { machine srv "$S_PUB"; for i in 0 1 2; do machine "load$((i + 1))" "${L_PUB[$i]}"; done
    echo "commit: $(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null)+worktree"
    echo "date: $(date -u '+%Y-%m-%d %H:%M UTC')"
    echo "plan: servers [$SERVERS], scenarios [$SCENARIOS], S1 conns [$CONNS], S6 conns [$IDLE_CONNS], sweep [$SWEEP_ARGS]"
    echo "simoom-bench: $(on "${L_PUB[0]}" "$SB version")"
  } > "$OUT/machine.txt"
  touch "$OUT/results.txt" "$OUT/run.log"
  for n in $SERVERS; do server_bench "$n"; done
  log "fetching histograms"
  mkdir -p "$OUT/hdr"
  scp -q "${SSH_OPTS[@]}" "root@${L_PUB[0]}:/root/out/*" "$OUT/hdr/" 2>/dev/null || true
  scp -q "${SSH_OPTS[@]}" "root@$S_PUB:/root/node/sar-*.log" "$OUT/hdr/" 2>/dev/null || true
  for f in "$OUT"/hdr/sar-*.log; do [ -f "$f" ] && mv "$f" "${f%.log}-srv.log"; done
}

sync() { # ship crates/simoom-bench and bench/ again, rebuild simoom-bench, restart the agents
  tar -C "$ROOT" --exclude='./bench/results' -czf "$STATE_DIR/sync.tgz" ./crates/simoom-bench ./bench ./scripts
  local i=0
  for h in "$S_PUB" "${L_PUB[@]}"; do
    local ip=""; [ "$h" != "$S_PUB" ] && ip="${L_PRIV[$i]}" && i=$((i + 1))
    { scp -q "${SSH_OPTS[@]}" "$STATE_DIR/sync.tgz" "root@$h:/root/sync.tgz" && on "$h" "cd /root/simoom && tar -xzf /root/sync.tgz && chmod +x bench/*/*.sh bench/competitors/*/*.sh && PATH=/root/.cargo/bin:\$PATH cargo build -q --release -p simoom-bench --target-dir /root/simoom/target && if [ -n '$ip' ]; then systemctl stop bench-agent; systemctl reset-failed bench-agent 2>/dev/null; systemd-run -q --unit=bench-agent --collect -p LimitNOFILE=1048576 -p TasksMax=infinity /root/simoom/target/release/simoom-bench agent --listen $ip:7070; fi"; } &
  done
  wait
}

summary() {
  python3 "$ROOT/bench/cloud/summarize.py" "$OUT/results.txt" --machine "$OUT/machine.txt" > "$OUT/summary.md"
  log "wrote $OUT/summary.md"
}

case "${1:-all}" in
  ship) ship ;;
  sync) sync ;;
  setup) setup ;;
  bench) bench ;;
  summary) summary ;;
  all) setup; bench; summary ;;
  *) echo "usage: $0 setup|bench|summary|all" >&2; exit 1 ;;
esac
