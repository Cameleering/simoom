#!/usr/bin/env python3
"""Summarize a simoom cloud-bench run (bench/cloud/run.sh) into Markdown tables.

    python3 bench/cloud/summarize.py bench/results/<date>-<label>/results.txt [--machine machine.txt] > summary.md

Reads the record lines (RESULT, SLO, METRIC, NIC, PEAK, BASE, IDLE, COLDSTART, SIZE, VERSION, SKIPPED,
FAILED). Stdlib only. Latencies in the RESULT lines are microseconds.
"""
import argparse
import re
import sys
from collections import defaultdict

ORDER = ["simoom", "nginx", "h2o", "haproxy", "envoy", "caddy", "hyper", "axum", "actix", "may-minihttp", "xitca", "ntex",
         "go-nethttp", "fasthttp", "netty", "vertx", "uws", "kestrel", "cameleer"]


def parse(path):
    recs = defaultdict(list)
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line or " " not in line:
            continue
        kind, rest = line.split(" ", 1)
        kv = dict(re.findall(r"(\w+)=(\S+)", rest))
        kv["_raw"] = rest
        recs[kind].append(kv)
    return recs


def num(v, default=None):
    try:
        return float(v)
    except (TypeError, ValueError):
        return default


def fmt(v, digits=0, unit=""):
    if v is None:
        return "-"
    if digits == 0:
        return f"{v:,.0f}{unit}"
    return f"{v:,.{digits}f}{unit}"


def servers_in(recs):
    seen = []
    for kind in ("VERSION", "RESULT", "SKIPPED", "IDLE"):
        for r in recs[kind]:
            s = r.get("server")
            if s and s not in seen:
                seen.append(s)
    return sorted(seen, key=lambda s: ORDER.index(s) if s in ORDER else 99)


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser()
    ap.add_argument("results")
    ap.add_argument("--machine")
    a = ap.parse_args()
    recs = parse(a.results)
    servers = servers_in(recs)
    out = []
    w = out.append
    w("# simoom cloud benchmark\n")
    w("_Generated by `bench/cloud/summarize.py` from `results.txt`; raw HdrHistogram files are in `hdr/`._\n")
    if a.machine:
        w("## Machines\n")
        w("```")
        for line in open(a.machine, encoding="utf-8"):
            w(line.rstrip())
        w("```\n")

    w("## Versions\n")
    w("| server | version | stripped binary |")
    w("|---|---|---:|")
    for s in servers:
        v = next((r["_raw"].split(" ", 1)[1] if " " in r["_raw"] else "" for r in recs["VERSION"] if r.get("server") == s), "")
        size = next((num(r.get("bytes")) for r in recs["SIZE"] if r.get("server") == s), None)
        skipped = any(r.get("server") == s for r in recs["SKIPPED"])
        w(f"| {s} | {'(setup failed) ' if skipped else ''}{v.strip()} | {fmt(size / 1024 if size else None, 0, ' KB')} |")
    w("")

    # S1 / S3: SLO throughput per connection count
    for scen, title in (("S1", "S1: GET, 13-byte reply, no pipelining"), ("S3", "S3: POST 1 KB JSON, echoed")):
        slos = [r for r in recs["SLO"] if r.get("scenario") == scen]
        if not slos:
            continue
        conns = sorted({int(r["conns"]) for r in slos})
        w(f"## {title}\n")
        w("**SLO throughput**: the highest open-loop rate (req/s) with p99 ≤ 1 ms, no errors and the rate achieved. "
          "`≥` marks a run where the search's top (1.05 × the closed-loop capacity at that connection count) passed, "
          "so the bound is the connection count, not the server. The closed-loop probe is in brackets.\n")
        w("| server | " + " | ".join(f"{c} conns" for c in conns) + " |")
        w("|---|" + "---:|" * len(conns))
        for s in servers:
            cells = []
            for c in conns:
                r = next((x for x in slos if x.get("server") == s and int(x["conns"]) == c), None)
                if r is None:
                    cells.append("-")
                    continue
                v = num(r.get("slo_rps"), 0)
                cap = "≥ " if r.get("capped") == "1" else ""
                cells.append(f"{cap}{fmt(v)} ({fmt(num(r.get('probe_rps')))})")
            w(f"| {s} | " + " | ".join(cells) + " |")
        w("")
        w(f"**Latency at 50 / 80 / 95% of the SLO throughput** (µs, p50 / p99 / p99.9; open loop, timed from the intended send time)\n")
        w("| server | conns | 50% | 80% | 95% |")
        w("|---|---:|---|---|---|")
        for s in servers:
            for c in conns:
                cells = []
                for pct in ("50", "80", "95"):
                    r = next((x for x in recs["RESULT"] if x.get("server") == s and x.get("scenario") == scen and x.get("conns") == str(c)
                              and x.get("phase") == "point" and x.get("pct") == pct), None)
                    cells.append("-" if r is None else f"{r.get('p50_us')} / {r.get('p99_us')} / {r.get('p999_us')}")
                if any(x != "-" for x in cells):
                    w(f"| {s} | {c} | " + " | ".join(cells) + " |")
        w("")

    if recs["METRIC"]:
        w("## Cost per request (at 80% of the SLO throughput)\n")
        w("CPU time is the server's cgroup CPU over the run divided by the requests; cycles, instructions and "
          "context switches come from `perf stat -G` on the server's cgroup, syscalls from bpftrace on it "
          "(`-` where the VM exposes no counters or the tool failed).\n")
        w("| server | conns | rate | CPU µs/req | cycles/req | instr/req | ctx sw/req | syscalls/req | server NIC rx/tx pkt/s |")
        w("|---|---:|---:|---:|---:|---:|---:|---:|---|")
        for s in servers:
            for r in (x for x in recs["METRIC"] if x.get("server") == s):
                nic = next((x for x in recs["NIC"] if x.get("server") == s and x.get("node") == "srv"), {})
                w(f"| {s} | {r.get('conns')} | {fmt(num(r.get('rate')))} | {r.get('cpu_us_per_req')} | {r.get('cycles_per_req')} | "
                  f"{r.get('instr_per_req')} | {r.get('ctxsw_per_req')} | {r.get('syscalls_per_req')} | "
                  f"{nic.get('rxpck_s', '-')} / {nic.get('txpck_s', '-')} |")
        w("")

    w("## Footprint\n")
    w("Memory is the summed PSS of the server's processes (`/proc/<pid>/smaps_rollup`); the per-connection figure is "
      "(PSS with the idle connections − PSS before) / established connections. Cold start is spawn to the first "
      "successful response, median of 10, timed on the server node with the server's own command line.\n")
    idle_conns = sorted({int(r["conns"]) for r in recs["IDLE"] if r.get("conns", "").isdigit()})
    head = "| server | base PSS | peak PSS under load | " + " | ".join(f"{c} idle: PSS, B/conn" for c in idle_conns) + " | cold start median (min–max) |"
    w(head)
    w("|---|---:|---:|" + "---:|" * len(idle_conns) + "---:|")
    for s in servers:
        base = next((num(r.get("pss_kb")) for r in recs["BASE"] if r.get("server") == s), None)
        peak = next((num(r.get("pss_kb")) for r in recs["PEAK"] if r.get("server") == s), None)
        cells = []
        for c in idle_conns:
            r = next((x for x in recs["IDLE"] if x.get("server") == s and x.get("conns") == str(c)), None)
            if r is None or r.get("failed"):
                cells.append("failed" if r else "-")
            else:
                est = int(r.get("established", 0))
                note = "" if est >= c * 0.99 else f" ({est} open)"
                cells.append(f"{fmt(num(r.get('pss_kb')) / 1024, 1, ' MB')}, {fmt(num(r.get('per_conn_b')))}{note}")
        cs = next((r for r in recs["COLDSTART"] if r.get("server") == s), None)
        csv = "-" if cs is None else f"{cs.get('median_ms')} ms ({cs.get('min_ms')}–{cs.get('max_ms')})"
        w(f"| {s} | {fmt(base / 1024 if base else None, 1, ' MB')} | {fmt(peak / 1024 if peak else None, 1, ' MB')} | " + " | ".join(cells) + f" | {csv} |")
    w("")

    w("## Load generator health\n")
    w("Every run reports the load nodes' CPU (the busiest of the three) and the generator's timer lag. "
      "A run where a load node passed 60% is flagged; its numbers may understate the server.\n")
    runs = recs["RESULT"]
    flagged = [r for r in runs if r.get("load_node_over_60pct") == "1"]
    worst = max((num(r.get("node_cpu_pct"), 0) for r in runs), default=0)
    lagp99 = max((num(r.get("lag_p99_us"), 0) for r in runs if r.get("phase") in ("step", "point") or r.get("scenario") == "cost"), default=0)
    w(f"- runs: {len(runs)}; flagged (a load node over 60% CPU): {len(flagged)}; highest load-node CPU: {worst:.1f}%")
    w(f"- worst open-loop timer lag p99 across runs: {lagp99:.0f} µs")
    for r in flagged:
        w(f"  - flagged: server={r.get('server')} scenario={r.get('scenario')} conns={r.get('conns')} phase={r.get('phase')} "
          f"rate={r.get('rate')} node_cpu={r.get('node_cpu_pct')}%")
    for kind in ("SKIPPED", "FAILED"):
        for r in recs[kind]:
            w(f"- {kind.lower()}: {r['_raw']}")
    w("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
